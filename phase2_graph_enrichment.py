import hashlib
import re
from pathlib import Path

import spacy
from spacy.matcher import PhraseMatcher

from document_processing import process_pdf
from semantic_chunking import semantic_chunking
from entity_extraction import extract_entities
from neo4j_connection import driver


PDF_PATH = "data3/mca(syllabus).pdf"
MODEL_NAME = "en_core_web_sm"
MIN_CONCEPT_WORDS = 1
MAX_CONCEPT_WORDS = 6

STOP_PHRASES = {
    "this paper", "course outcome", "course outcomes", "text book",
    "text books", "reference book", "reference books", "suggested reading",
    "suggested readings", "maximum marks", "question number",
    "unit", "semester", "mca", "students", "student", "ability",
    "introduction", "conclusion", "example", "examples"
}


def stable_id(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def clean_phrase(value):
    value = re.sub(r"\s+", " ", value).strip(" \t.,:;()[]{}")
    return value


def canonicalize(phrase, nlp):
    doc = nlp(phrase)
    tokens = [
        token.lemma_.lower()
        for token in doc
        if not token.is_stop and not token.is_punct and not token.is_space
    ]
    return " ".join(tokens)


def valid_concept(phrase):
    phrase = clean_phrase(phrase)
    words = phrase.split()
    key = phrase.casefold()

    if not phrase or key in STOP_PHRASES:
        return False
    if not MIN_CONCEPT_WORDS <= len(words) <= MAX_CONCEPT_WORDS:
        return False
    if len(phrase) < 3 or len(phrase) > 80:
        return False
    if re.fullmatch(r"[\W\d_]+", phrase):
        return False
    if re.search(r"\b(ability to|students will|course will|this paper)\b",
                 phrase, re.IGNORECASE):
        return False
    return True


def extract_concepts(text, nlp):
    doc = nlp(text)
    candidates = {}

    # Noun chunks are the main concept candidates.
    for chunk in doc.noun_chunks:
        phrase = clean_phrase(chunk.text)
        if valid_concept(phrase):
            key = canonicalize(phrase, nlp)
            if key:
                candidates.setdefault(key, phrase)

    # Keep useful named entities that noun-chunk extraction may miss.
    for ent in doc.ents:
        if ent.label_ in {"ORG", "PRODUCT", "WORK_OF_ART", "EVENT"}:
            phrase = clean_phrase(ent.text)
            if valid_concept(phrase):
                key = canonicalize(phrase, nlp)
                if key:
                    candidates.setdefault(key, phrase)

    return candidates


def load_nlp():
    try:
        return spacy.load(MODEL_NAME)
    except OSError as exc:
        raise RuntimeError(
            f"spaCy model '{MODEL_NAME}' is missing. Run:\n"
            "pip install spacy\n"
            "python -m spacy download en_core_web_sm"
        ) from exc


def enrich_graph(tx, document_id, entities, chunks, nlp):
    # Rebuild only concepts previously generated by the Phase-1 topic seed.
    tx.run("""
        MATCH (c:Concept {extraction_method: 'topic_seed'})
        DETACH DELETE c
    """)

    concept_records = {}
    chunk_records = []

    for index, chunk in enumerate(chunks, start=1):
        chunk_id = stable_id(
            f"{document_id}|Chunk|{index}|{chunk['text']}"
        )
        chunk_pages = sorted(set(chunk.get("page_numbers", [])))
        chunk_records.append({
            "chunk_id": chunk_id,
            "text": chunk["text"],
            "pages": chunk_pages
        })

        for canonical, display_name in extract_concepts(chunk["text"], nlp).items():
            concept_id = stable_id(f"Concept|{canonical}")
            record = concept_records.setdefault(concept_id, {
                "concept_id": concept_id,
                "name": display_name,
                "normalized_name": canonical,
                "chunk_ids": set(),
                "pages": set()
            })
            record["chunk_ids"].add(chunk_id)
            record["pages"].update(chunk_pages)

    # Store concepts globally by normalized identity and connect to source chunks.
    for record in concept_records.values():
        tx.run("""
            MERGE (c:Concept {concept_id: $concept_id})
            ON CREATE SET c.name = $name
            SET c.normalized_name = $normalized_name,
                c.extraction_method = 'spacy_noun_phrase',
                c.page_numbers = $pages
        """,
            concept_id=record["concept_id"],
            name=record["name"],
            normalized_name=record["normalized_name"],
            pages=sorted(record["pages"])
        )

        for chunk_id in record["chunk_ids"]:
            tx.run("""
                MATCH (c:Concept {concept_id: $concept_id})
                MATCH (ch:Chunk {chunk_id: $chunk_id})
                MERGE (c)-[:MENTIONED_IN]->(ch)
            """, concept_id=record["concept_id"], chunk_id=chunk_id)

    # Associate concepts with a Topic only when that topic phrase occurs
    # in the source chunk. This avoids page-only, overly broad associations.
    topic_count = 0
    for entity in entities:
        if entity["type"] != "Topic":
            continue

        subject = entity.get("subject")
        unit = entity.get("unit")
        topic_name = clean_phrase(entity["name"])
        if not subject or not unit or not topic_name:
            continue

        topic_id = stable_id(
            f"{document_id}|{subject}|{unit}|Topic|{topic_name.casefold()}"
        )

        matching_chunks = [
            item for item in chunk_records
            if topic_name.casefold() in item["text"].casefold()
        ]

        for item in matching_chunks:
            tx.run("""
                MATCH (t:Topic {topic_id: $topic_id})
                MATCH (c:Concept)-[:MENTIONED_IN]->(
                    ch:Chunk {chunk_id: $chunk_id}
                )
                MERGE (t)-[:HAS_CONCEPT]->(c)
            """, topic_id=topic_id, chunk_id=item["chunk_id"])
            topic_count += 1

    return len(concept_records), topic_count


def main():
    pdf_path = Path(PDF_PATH).resolve()
    if not pdf_path.exists():
        raise FileNotFoundError(f"PDF not found: {pdf_path}")

    nlp = load_nlp()
    document = process_pdf(str(pdf_path))
    chunks = semantic_chunking(document["pages"])
    entities = extract_entities(document["pages"])

    document_id = stable_id(str(pdf_path))

    with driver.session() as session:
        # Confirm Phase 1 graph exists before enriching it.
        result = session.run("""
            MATCH (d:Document {document_id: $document_id})
            RETURN count(d) AS total
        """, document_id=document_id).single()

        if not result or result["total"] == 0:
            raise RuntimeError(
                "Phase 1 graph not found. Run complete_graph_build.py first."
            )

        concepts, topic_links = session.execute_write(
            enrich_graph, document_id, entities, chunks, nlp
        )

    print("Phase 2 graph enrichment completed.")
    print("Concepts extracted:", concepts)
    print("Topic-concept links created:", topic_links)
    print("Extraction method: spaCy noun phrases + lemmatization")
    print("Note: This is NLP-based extraction, not LLM-based extraction.")


if __name__ == "__main__":
    try:
        main()
    finally:
        driver.close()
